import assert from 'node:assert/strict';
import { createSlashCommands } from '../src/runtime/card-runtime/host/slash-commands.js';
const readVariable=(variables,path)=>variables[path];
const mutateVariable=(variables,operation,path,value)=>{
  const next={...variables};
  if(operation==='set') next[path]=value;
  else if(operation==='delete') delete next[path];
  else if(operation==='add') next[path]=(next[path]??0)+value;
  else if(operation==='sub') next[path]=(next[path]??0)-value;
  return next;
};
const slash=createSlashCommands({Xu:text=>text,Uu:readVariable,Gu:mutateVariable});
assert.deepEqual(Object.keys(slash),['tp','ip','op','sp']);
assert.deepEqual(slash.tp('send "hello world" name=value'),['send','hello world','name=value']);
assert.deepEqual(slash.tp("echo 'a b' c"),['echo','a b','c']);
assert.equal(slash.op('10','gt','2'),true);
assert.equal(slash.op('abc','includes','bc'),true);
assert.equal(slash.op('a','unknown','b'),false);
const sent=[];const context={characterName:'Hero',userPersonaName:'Reader',variables:{hp:1},setVariables(value){this.variables=value;},sendMessage(text,role){sent.push({text,role});}};
assert.equal(slash.ip('{{char}}/{{user}}/{{dice:1d1}}/{{getvar::hp}}',context),'Hero/Reader/1/1');
assert.equal(slash.ip('{{setvar::hp::3}}{{getvar::hp}}',context),'3');
assert.equal(await slash.sp.setvar(['key=hp','value=4'],context),'4');
assert.equal(await slash.sp.incvar(['hp','2'],context),'6');
assert.equal(await slash.sp.getvar(['hp'],context),'6');
await slash.sp.send([],context,'Hello');assert.deepEqual(sent,[{text:'Hello',role:'user'}]);
await slash.sp.flushvar(['hp'],context);assert.equal(context.variables.hp,undefined);
const execution={labels:{next:5},pc:0};await slash.sp.goto(['next'],context,'',execution);assert.equal(execution.pc,5);
assert.equal(await slash.sp.pass([],context,'value'),'value');
console.log('F01 readable slash command bindings: parsing, macros and handler contracts OK');
