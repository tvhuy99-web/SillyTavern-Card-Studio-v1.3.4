import assert from 'node:assert/strict';
import { createRuntimeCompatibilityData } from '../src/runtime/card-runtime/host/compatibility-data.js';
import { createRuntimeContextAdapters } from '../src/runtime/card-runtime/host/context-adapters.js';
import { createRuntimeDiagnostics } from '../src/diagnostics/card-runtime-diagnostics.js';
import { createFeatureSettings } from '../src/features/state/feature-settings.js';

const compatibility=createRuntimeCompatibilityData({__stsResolveRuntimeMessageIndex:(index,count)=>index<0?count+index:index});
assert.deepEqual(compatibility.resolveMessageRange('1-{{lastMessageId}}',4),[1,2,3]);
assert.deepEqual(compatibility.resolveMessageRange('-2--1',4),[2,3]);
assert.deepEqual(compatibility.resolveMessageRange('99',4),[]);
assert.deepEqual(compatibility.applySamplingOverrides({temperature:0.7,max_context:2048},{temp:1}),{temp:0.7,truncation_length:2048});
assert.throws(()=>compatibility.assertPayloadSize({data:'abcdef'},2),/byte limit/);
const message=compatibility.toRuntimeMessage({role:'model',content:'hi',swipes:['hi','hello'],swipe_id:1,contextState:{hp:1}},0,'User','Hero',true);
assert.equal(message.name,'Hero');assert.equal(message.role,'assistant');assert.equal(message.swipe_id,1);assert.deepEqual(message.swipes_data,[{},{}]);
const state={sessionId:'chat',card:{name:'Hero'},preset:{name:'default',temp:1}};
const adapter=createRuntimeContextAdapters({sessionStore:{getState:()=>state},cloneRuntimeValue:structuredClone});
assert.deepEqual(adapter.buildRuntimeScope(2),{chatId:'chat',characterId:'Hero',presetName:'default',messageId:2});
assert.deepEqual(adapter.resolveGenerationPreset({custom_api:{temperature:'0.5',top_k:'unset'}}),{name:'default',temp:0.5});
assert.equal(state.preset.temp,1);
assert.equal(adapter.classifyRuntimeError('RPC timeout'),'CARD_RUNTIME_RPC_TIMEOUT');
assert.equal(await adapter.readTextPayload(new Uint8Array([65,66])),'AB');
const diagnostics=createRuntimeDiagnostics();
const result=diagnostics.normalizeDiagnostic({messageId:0,details:{text:'x'.repeat(5000)}},{code:'CARD_RUNTIME_RPC_FAILED'});
assert.equal(result.messageId,0);assert.equal(result.details.text.length,4000);assert.match(diagnostics.formatDiagnostic(result),/Message ID: 0/);
const store=new Map([['scan','{"mode":"semantic"}']]);
const settings=createFeatureSettings({storage:{getItem:key=>store.get(key),setItem:(key,value)=>store.set(key,value)},smartScanSettingsKey:'scan',smartScanDefaults:{enabled:true},__stsMigrateSmartScanStickySettings:value=>({...value,sticky:true}),__stsMarkSmartScanStickySettingsSaved:value=>({...value,saved:true})});
assert.deepEqual(settings.getSmartScanSettings(),{enabled:true,mode:'semantic',sticky:true});
assert.equal(JSON.parse(store.get('scan')).sticky,true);
settings.saveSmartScanSettings({enabled:false});assert.equal(JSON.parse(store.get('scan')).saved,true);
console.log('F01 readable runtime and settings locals: compatibility behavior OK');
